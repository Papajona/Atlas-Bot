"""Preflight controls for an isolated customer paper ledger.

No real-money tables, adapters, or customer-fund sessions are imported here. The
paper database URL is never allowed to silently fall back to DATABASE_URL.
Execution remains disabled until a reviewed staging preflight passes.
"""
from __future__ import annotations

from collections.abc import Mapping, Sequence
from decimal import Decimal, InvalidOperation, localcontext
import hashlib
import json
import re
import uuid
from typing import Any
from sqlalchemy import text
from sqlalchemy.engine import URL, make_url
from sqlalchemy.ext.asyncio import create_async_engine

from .config import settings


REAL_MONEY_TABLES = (
    "customer_ledger_accounts", "ledger_journals", "ledger_journal_lines",
    "ledger_entries", "withdrawals", "wallets", "funding_transactions", "tron_sweeps",
)
PAPER_TABLES = (
    "customer_paper.accounts", "customer_paper.journals", "customer_paper.journal_lines",
    "customer_paper.orders", "customer_paper.order_events", "customer_paper.fills",
    "customer_paper.position_events",
)
# Shared market-bar budgets contain only public OHLCV provenance and aggregate capacity,
# never customer identifiers or financial balances. They use a separate explicit policy.
PAPER_GLOBAL_TABLES = ("customer_paper.market_bar_budgets", "customer_paper.market_bar_allocations")


def _tenant_policy_expression_is_exact(expression: Any) -> bool:
    """Accept only the exact tenant predicate generated by the paper schema migration.

    PostgreSQL combines permissive policies with OR, so checking only for the presence
    of an app.customer_id substring is unsafe. The caller also requires exactly one
    policy per table and checks its command, name and role.
    """
    normalized = re.sub(r"\s+", "", str(expression or "")).strip("()").casefold()
    # PostgreSQL's pg_policies deparser may parenthesize NULLIF(...) before its
    # bigint cast. Permit that equivalent rendering while keeping the predicate
    # grammar exact (no extra clauses, operators, or columns).
    return re.fullmatch(
        r"customer_id=(?:nullif\(current_setting\('app\.customer_id'(?:::text)?,true\),''(?:::text)?\)|\(nullif\(current_setting\('app\.customer_id'(?:::text)?,true\),''(?:::text)?\)\))::bigint",
        normalized,
    ) is not None


def _tenant_policy_roles_are_exact(value: Any, expected_role: str) -> bool:
    """Compare pg_policies.roles safely across driver array representations."""
    if isinstance(value, str):
        raw = value.strip()
        if not (raw.startswith("{") and raw.endswith("}")):
            return False
        body = raw[1:-1]
        # This schema permits only the single simple role name provisioned by the
        # reviewed SQL runbook; commas or empty values must fail closed.
        if not body or "," in body:
            return False
        roles = {body.strip('"').casefold()}
    elif isinstance(value, Sequence) and not isinstance(value, (bytes, bytearray)):
        roles = {str(item).casefold() for item in value}
    else:
        return False
    return roles == {str(expected_role).casefold()}



def _tenant_policy_validation_error(
    policy: Mapping[str, Any] | None, expected_role: str
) -> str | None:
    """Validate every security-relevant pg_policies field and explain failures."""
    if policy is None:
        return "MISSING_OR_MULTIPLE_POLICIES"
    failures = []
    if str(policy.get("policyname") or "") != "customer_paper_tenant":
        failures.append("NAME")
    if str(policy.get("cmd") or "").upper() != "ALL":
        failures.append("COMMAND")
    # pg_policies.permissive is textual ("PERMISSIVE"/"RESTRICTIVE"), so
    # bool("RESTRICTIVE") is true and is not a safe validation.
    if str(policy.get("permissive") or "").upper() != "PERMISSIVE":
        failures.append("NOT_PERMISSIVE")
    if not _tenant_policy_expression_is_exact(policy.get("qual")):
        failures.append("USING_EXPRESSION")
    if not _tenant_policy_expression_is_exact(policy.get("with_check")):
        failures.append("WITH_CHECK_EXPRESSION")
    if not _tenant_policy_roles_are_exact(policy.get("roles"), expected_role):
        failures.append("ROLE")
    return ",".join(failures) or None



def _postgres_url(value: str) -> URL:
    try:
        url = make_url(value)
    except Exception as exc:
        raise ValueError("database URL is malformed") from exc
    if not url.drivername.startswith("postgresql"):
        raise ValueError("customer paper isolation requires PostgreSQL URLs")
    if not url.host or not url.database or not url.username or not url.password:
        raise ValueError("database URL must include host, database, username and password")
    # Async preflight always uses asyncpg; normalize plain postgresql URLs.
    if url.drivername == "postgresql":
        url = url.set(drivername="postgresql+asyncpg")
    if url.drivername != "postgresql+asyncpg":
        raise ValueError("database URL must use the postgresql+asyncpg driver")
    return url


def validate_database_url_pair(
    primary_url: str, paper_url: str, *, allow_same_database: bool = False
) -> dict[str, Any]:
    """Validate distinct runtime credentials and the selected database isolation boundary.

    Shared-database mode is an explicit opt-in and remains gated by the live ACL/RLS preflight.
    """
    primary = _postgres_url(primary_url)
    paper = _postgres_url(paper_url)
    same_database = (
        primary.host.casefold(), primary.port or 5432, primary.database
    ) == (
        paper.host.casefold(), paper.port or 5432, paper.database
    )
    if same_database and not allow_same_database:
        raise ValueError(
            "customer paper ledger must use a separate PostgreSQL database unless "
            "shared-database schema isolation is explicitly enabled"
        )
    if primary.username == paper.username:
        raise ValueError("customer paper ledger requires a distinct PostgreSQL runtime role")
    if primary.password == paper.password:
        raise ValueError("customer paper ledger requires a distinct database credential")
    return {
        "primary_host": primary.host.casefold(),
        "paper_host": paper.host.casefold(),
        "same_server": (primary.host.casefold(), primary.port or 5432) == (paper.host.casefold(), paper.port or 5432),
        "same_database": same_database,
        "isolation_mode": "shared_database_schema" if same_database else "separate_database",
        "primary_database": primary.database,
        "paper_database": paper.database,
        "distinct_runtime_roles": True,
        "distinct_credentials": True,
    }

async def preflight_isolated_customer_paper_ledger(
    *,
    primary_url: str | None = None,
    paper_url: str | None = None,
    require_enabled: bool = True,
) -> dict[str, Any]:
    """Verify DB identities, RLS, paper schema, and no privileges on real-money tables.

    This is a read-only preflight. It does not create the schema, write paper orders,
    enable customer paper trading, or certify the service without a real staging run.
    """
    if require_enabled and not settings.customer_paper_ledger_enabled:
        return {"status": "BLOCKED", "reason": "CUSTOMER_PAPER_LEDGER_FEATURE_DISABLED"}
    primary_value = primary_url if primary_url is not None else settings.database_url
    paper_value = paper_url if paper_url is not None else settings.customer_paper_database_url
    if not paper_value:
        return {"status": "BLOCKED", "reason": "CUSTOMER_PAPER_DATABASE_URL_MISSING"}
    try:
        pair = validate_database_url_pair(
            primary_value,
            paper_value,
            allow_same_database=bool(settings.customer_paper_shared_database_enabled),
        )
    except ValueError as exc:
        return {"status": "BLOCKED", "reason": "DATABASE_URL_ISOLATION_INVALID", "detail": str(exc)}
    same_database = bool(pair.get("same_database"))

    engine = create_async_engine(
        paper_value if "+asyncpg" in paper_value else _postgres_url(paper_value).render_as_string(hide_password=False),
        pool_pre_ping=True,
        connect_args={"server_settings": {"statement_timeout": "10000"}},
    )
    try:
        async with engine.connect() as conn:
            identity = (await conn.exec_driver_sql(
                "SELECT current_database(), current_user, session_user, "
                "current_setting('transaction_read_only'), "
                "(SELECT rolcanlogin FROM pg_roles WHERE rolname = current_user), "
                "(SELECT rolsuper OR rolcreaterole OR rolcreatedb OR rolreplication "
                " FROM pg_roles WHERE rolname = current_user), "
                "(SELECT rolinherit OR rolbypassrls FROM pg_roles WHERE rolname = current_user), "
                "(SELECT count(*) FROM pg_auth_members m JOIN pg_roles r ON r.oid=m.member "
                " WHERE r.rolname=current_user), "
                "(SELECT count(*) FROM pg_auth_members m JOIN pg_roles r ON r.oid=m.roleid "
                " WHERE r.rolname=current_user), "
                "has_schema_privilege(current_user, 'public', 'USAGE'), "
                "has_schema_privilege(current_user, 'public', 'CREATE'), "
                "(SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname='customer_paper')), "
                "COALESCE((SELECT has_schema_privilege(current_user, n.oid, 'USAGE') "
                "FROM pg_namespace n WHERE n.nspname='customer_paper'), false), "
                "COALESCE((SELECT has_schema_privilege(current_user, n.oid, 'CREATE') "
                "FROM pg_namespace n WHERE n.nspname='customer_paper'), false)"
            )).one()
            (db_name, role_name, session_role_name, read_only, role_can_login, elevated,
             unsafe_rls_role, memberships, member_count, public_schema_usage, public_schema_create,
             paper_schema_present, paper_schema_usage, paper_schema_create) = identity
            if db_name != _postgres_url(paper_value).database:
                return {"status": "BLOCKED", "reason": "PAPER_DATABASE_IDENTITY_MISMATCH"}
            configured_paper_role = _postgres_url(paper_value).username
            if role_name != configured_paper_role or session_role_name != role_name:
                return {"status": "BLOCKED", "reason": "PAPER_ROLE_IDENTITY_MISMATCH"}
            if not bool(role_can_login):
                return {"status": "BLOCKED", "reason": "PAPER_RUNTIME_ROLE_CANNOT_LOGIN"}
            if role_name == _postgres_url(primary_value).username:
                return {"status": "BLOCKED", "reason": "PAPER_ROLE_REUSES_PRIMARY_ROLE"}
            if (
                bool(elevated)
                or bool(unsafe_rls_role)
                or int(memberships) != 0
                or int(member_count) != 0
            ):
                return {"status": "BLOCKED", "reason": "PAPER_ROLE_HAS_UNSAFE_DATABASE_CAPABILITIES"}
            if str(read_only).lower() not in {"off", "false", "f"}:
                # A global read-only connection is insufficient to verify order write grants.
                return {"status": "BLOCKED", "reason": "PAPER_CONNECTION_IS_READ_ONLY"}
            # PostgreSQL commonly grants USAGE on the public schema to PUBLIC.
            # This permits name resolution but grants no object privileges by itself;
            # all relations/sequences in the primary database are checked below, and
            # schema CREATE remains forbidden. Do not require a cluster-wide change to
            # the default public USAGE grant simply to run the isolated paper ledger.
            if bool(public_schema_create):
                return {"status": "BLOCKED", "reason": "PAPER_ROLE_HAS_UNEXPECTED_PUBLIC_SCHEMA_CREATE"}
            if not bool(paper_schema_present):
                return {"status": "BLOCKED", "reason": "PAPER_SCHEMA_NOT_PROVISIONED"}
            if not bool(paper_schema_usage):
                return {"status": "BLOCKED", "reason": "PAPER_SCHEMA_USAGE_MISSING"}
            if bool(paper_schema_create):
                return {"status": "BLOCKED", "reason": "PAPER_SCHEMA_CREATE_ALLOWED"}
            table_rows = (await conn.execute(text(
                """
                SELECT n.nspname || '.' || c.relname AS table_name,
                       c.relkind::text AS relkind, c.relrowsecurity, c.relforcerowsecurity,
                       has_table_privilege(current_user, c.oid, 'SELECT') AS can_select,
                       has_table_privilege(current_user, c.oid, 'INSERT') AS can_insert,
                       has_table_privilege(current_user, c.oid, 'UPDATE') AS can_update,
                       has_table_privilege(current_user, c.oid, 'DELETE') AS can_delete
                FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
                WHERE (n.nspname='customer_paper' AND c.relname = ANY(:paper_table_names))
                   OR (n.nspname='public' AND c.relname = ANY(:real_tables))
                """),
                {"real_tables": list(REAL_MONEY_TABLES), "paper_table_names": [name.split(".", 1)[1] for name in PAPER_TABLES + PAPER_GLOBAL_TABLES]},
            )).mappings().all()
            by_name = {str(row["table_name"]): row for row in table_rows}
            missing_paper = sorted(set(PAPER_TABLES + PAPER_GLOBAL_TABLES) - set(by_name))
            if missing_paper:
                return {"status": "BLOCKED", "reason": "PAPER_SCHEMA_NOT_PROVISIONED",
                        "missing_tables": missing_paper, "identity": {"database": db_name, "role": role_name}}
            insecure_paper = []
            for name in PAPER_TABLES + PAPER_GLOBAL_TABLES:
                row = by_name[name]
                if row["relkind"] not in {"r", "p"}:
                    insecure_paper.append(f"{name}:NOT_A_TABLE")
                if not bool(row["relrowsecurity"]) or not bool(row["relforcerowsecurity"]):
                    insecure_paper.append(f"{name}:RLS_NOT_FORCED")
                if not bool(row["can_select"]) or not bool(row["can_insert"]):
                    insecure_paper.append(f"{name}:SELECT_OR_INSERT_MISSING")
                if bool(row["can_update"]):
                    insecure_paper.append(f"{name}:UPDATE_ALLOWED")
                if bool(row["can_delete"]):
                    insecure_paper.append(f"{name}:DELETE_ALLOWED")
            paper_sequence_rows = (await conn.execute(text(
                """
                SELECT c.oid::regclass::text AS sequence_name,
                       has_sequence_privilege(current_user, c.oid, 'USAGE') AS can_use
                FROM pg_class c
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = 'customer_paper'
                  AND c.relkind = 'S'
                  AND c.oid IN (
                      NULLIF(pg_get_serial_sequence('customer_paper.accounts', 'id'), '')::regclass,
                      NULLIF(pg_get_serial_sequence('customer_paper.journal_lines', 'id'), '')::regclass,
                      NULLIF(pg_get_serial_sequence('customer_paper.order_events', 'id'), '')::regclass,
                      NULLIF(pg_get_serial_sequence('customer_paper.position_events', 'id'), '')::regclass
                  )
                """
            ))).mappings().all()
            expected_sequences = {
                "customer_paper.accounts_id_seq",
                "customer_paper.journal_lines_id_seq",
                "customer_paper.order_events_id_seq",
                "customer_paper.position_events_id_seq",
            }
            observed_sequences = {str(row["sequence_name"]) for row in paper_sequence_rows}
            if (
                observed_sequences != expected_sequences
                or any(not bool(row["can_use"]) for row in paper_sequence_rows)
            ):
                return {
                    "status": "BLOCKED",
                    "reason": "PAPER_SEQUENCE_PRIVILEGES_UNSAFE",
                    "sequences": [
                        {
                            "name": str(row["sequence_name"]),
                            "can_use": bool(row["can_use"]),
                        }
                        for row in paper_sequence_rows
                    ],
                }
            policy_rows = (await conn.execute(text(
                "SELECT policyname, permissive, cmd, tablename, "
                "coalesce(qual,'') AS qual, coalesce(with_check,'') AS with_check, roles "
                "FROM pg_policies WHERE schemaname='customer_paper'"
            ))).mappings().all()
            policy_by_table: dict[str, list[Mapping[str, Any]]] = {}
            for policy in policy_rows:
                policy_by_table.setdefault(str(policy["tablename"]), []).append(policy)
            for table in (name.split(".", 1)[1] for name in PAPER_TABLES):
                candidates = policy_by_table.get(table, [])
                row = candidates[0] if len(candidates) == 1 else None
                policy_error = _tenant_policy_validation_error(row, str(role_name))
                if len(candidates) != 1:
                    policy_error = "MISSING" if not candidates else "MULTIPLE"
                if policy_error:
                    insecure_paper.append(
                        f"customer_paper.{table}:TENANT_POLICY_INVALID_{policy_error}"
                    )
            # These global tables contain only public bar metadata and aggregate fill capacity,
            # never customer IDs, positions, balances or journals. Their single policy is global
            # only for the dedicated backend role; RLS remains forced and direct API roles receive
            # no table privileges.
            for global_table in (name.split(".", 1)[1] for name in PAPER_GLOBAL_TABLES):
                candidates = policy_by_table.get(global_table, [])
                row = candidates[0] if len(candidates) == 1 else None
                if len(candidates) != 1:
                    insecure_paper.append(
                        f"customer_paper.{global_table}:GLOBAL_POLICY_INVALID_" + ("MISSING" if not candidates else "MULTIPLE")
                    )
                    continue
                normalized_using = re.sub(r"\\s+", "", str(row.get("qual") or "")).strip("()").casefold()
                normalized_check = re.sub(r"\\s+", "", str(row.get("with_check") or "")).strip("()").casefold()
                if str(row.get("policyname") or "") != "customer_paper_bar_budget_backend":
                    insecure_paper.append(f"customer_paper.{global_table}:GLOBAL_POLICY_INVALID_NAME")
                if str(row.get("cmd") or "").upper() != "ALL":
                    insecure_paper.append(f"customer_paper.{global_table}:GLOBAL_POLICY_INVALID_COMMAND")
                if str(row.get("permissive") or "").upper() != "PERMISSIVE":
                    insecure_paper.append(f"customer_paper.{global_table}:GLOBAL_POLICY_INVALID_PERMISSIVENESS")
                if normalized_using != "true" or normalized_check != "true":
                    insecure_paper.append(f"customer_paper.{global_table}:GLOBAL_POLICY_INVALID_PREDICATE")
                if not _tenant_policy_roles_are_exact(row.get("roles"), str(role_name)):
                    insecure_paper.append(f"customer_paper.{global_table}:GLOBAL_POLICY_INVALID_ROLE")

            required_bar_triggers = {
                "trg_customer_paper_market_bar_budgets_immutable",
                "trg_customer_paper_market_bar_allocations_immutable",
                "trg_customer_paper_market_bar_allocations_capacity",
            }
            trigger_rows = (await conn.execute(text(
                """
                SELECT t.tgname AS trigger_name, t.tgenabled AS enabled
                FROM pg_trigger t
                JOIN pg_class c ON c.oid=t.tgrelid
                JOIN pg_namespace n ON n.oid=c.relnamespace
                WHERE n.nspname='customer_paper'
                  AND c.relname IN ('market_bar_budgets','market_bar_allocations')
                  AND NOT t.tgisinternal
                """
            ))).mappings().all()
            enabled_triggers = {
                str(row["trigger_name"]) for row in trigger_rows
                if str(row["enabled"]) in {"O", "A"}
            }
            missing_bar_triggers = sorted(required_bar_triggers - enabled_triggers)
            if missing_bar_triggers:
                insecure_paper.append("customer_paper:BAR_CAPACITY_TRIGGER_MISSING:" + ",".join(missing_bar_triggers))
            if insecure_paper:
                return {"status": "BLOCKED", "reason": "PAPER_SCHEMA_PRIVILEGES_UNSAFE",
                        "findings": insecure_paper}
            exposed_real_tables = []
            for name in REAL_MONEY_TABLES:
                row = by_name.get("public." + name)
                if row is None:
                    continue
                for permission in ("can_select", "can_insert", "can_update", "can_delete"):
                    if bool(row[permission]):
                        exposed_real_tables.append(f"public.{name}:{permission}")
            if exposed_real_tables:
                return {"status": "BLOCKED", "reason": "PAPER_ROLE_HAS_REAL_MONEY_TABLE_PRIVILEGES",
                        "privileges": sorted(exposed_real_tables)}

            # Inspect the actual primary database as the primary runtime role. Checking
            # public tables only inside the paper database does not prove that the
            # paper role lacks privileges on the real customer ledger in the primary DB.
            primary_engine = create_async_engine(
                _postgres_url(primary_value).render_as_string(hide_password=False),
                pool_pre_ping=True,
                connect_args={"server_settings": {"statement_timeout": "10000"}},
            )
            try:
                async with primary_engine.connect() as primary_conn:
                    primary_db, primary_role = (await primary_conn.exec_driver_sql(
                        "SELECT current_database(), current_user"
                    )).one()
                    if primary_db != _postgres_url(primary_value).database:
                        return {"status": "BLOCKED", "reason": "PRIMARY_DATABASE_IDENTITY_MISMATCH"}
                    # PostgreSQL roles are cluster-local. If the paper role belongs to
                    # a separate database cluster, it may not exist in this cluster.
                    # The privilege probes below INNER JOIN pg_roles first, so absence
                    # yields no exposed privileges rather than a "role does not exist"
                    # exception; any same-named role that does exist is fully inspected.
                    primary_paper_role = (await primary_conn.execute(text(
                        """
                        SELECT
                            r.rolsuper OR r.rolcreaterole OR r.rolcreatedb OR r.rolreplication AS elevated,
                            r.rolinherit OR r.rolbypassrls AS unsafe_rls_role,
                            (SELECT count(*) FROM pg_auth_members m WHERE m.member = r.oid) AS memberships,
                            (SELECT count(*) FROM pg_auth_members m WHERE m.roleid = r.oid) AS member_count
                        FROM pg_roles r
                        WHERE r.rolname = CAST(:paper_role AS name)
                        """
                    ), {"paper_role": role_name})).mappings().first()
                    paper_role_present_on_primary = primary_paper_role is not None
                    if primary_paper_role is not None and (
                        bool(primary_paper_role["elevated"])
                        or bool(primary_paper_role["unsafe_rls_role"])
                        or int(primary_paper_role["memberships"]) != 0
                        or int(primary_paper_role["member_count"]) != 0
                    ):
                        return {
                            "status": "BLOCKED",
                            "reason": "PAPER_ROLE_HAS_UNSAFE_PRIMARY_ROLE_CAPABILITIES",
                        }
                    primary_schema_rows = (await primary_conn.execute(text(
                        """
                        SELECT n.nspname,
                               has_schema_privilege(r.oid, n.oid, 'USAGE') AS can_use,
                               has_schema_privilege(r.oid, n.oid, 'CREATE') AS can_create
                        FROM pg_namespace n
                        JOIN pg_roles r ON r.rolname = CAST(:paper_role AS name)
                        WHERE n.nspname NOT LIKE 'pg_%'
                          AND n.nspname <> 'information_schema'
                          AND (NOT :same_database OR n.nspname <> 'customer_paper')
                        """
                    ), {"paper_role": role_name, "same_database": same_database})).mappings().all()
                    # PostgreSQL normally grants USAGE on the "public" schema to
                    # PUBLIC. That alone does not grant table/function privileges and
                    # would make every distinct paper role fail preflight by default.
                    # Reject CREATE anywhere and USAGE on every non-public schema;
                    # the checks below separately inspect all table/view and sequence
                    # ACLs in the primary database.
                    schema_exposure = [
                        f"{row['nspname']}:{permission}"
                        for row in primary_schema_rows
                        for permission, value in (("USAGE", row["can_use"]), ("CREATE", row["can_create"]))
                        if bool(value) and (
                            permission == "CREATE" or str(row["nspname"]) != "public"
                        )
                    ]
                    if schema_exposure:
                        return {
                            "status": "BLOCKED",
                            "reason": "PAPER_ROLE_HAS_PRIMARY_SCHEMA_ACCESS",
                            "privileges": sorted(schema_exposure),
                        }
                    primary_table_rows = (await primary_conn.execute(text(
                        """
                        SELECT n.nspname || '.' || c.relname AS table_name,
                               has_table_privilege(r.oid, c.oid, 'SELECT') AS can_select,
                               has_table_privilege(r.oid, c.oid, 'INSERT') AS can_insert,
                               has_table_privilege(r.oid, c.oid, 'UPDATE') AS can_update,
                               has_table_privilege(r.oid, c.oid, 'DELETE') AS can_delete,
                               has_table_privilege(r.oid, c.oid, 'TRUNCATE') AS can_truncate,
                               has_table_privilege(r.oid, c.oid, 'REFERENCES') AS can_reference,
                               has_table_privilege(r.oid, c.oid, 'TRIGGER') AS can_trigger
                        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                        JOIN pg_roles r ON r.rolname = CAST(:paper_role AS name)
                        WHERE n.nspname NOT LIKE 'pg_%'
                          AND n.nspname <> 'information_schema'
                          AND (NOT :same_database OR n.nspname <> 'customer_paper')
                          AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
                        """
                    ), {"paper_role": role_name, "same_database": same_database})).mappings().all()
                    primary_exposure = []
                    for row in primary_table_rows:
                        for permission in (
                            "can_select", "can_insert", "can_update", "can_delete",
                            "can_truncate", "can_reference", "can_trigger",
                        ):
                            if bool(row[permission]):
                                primary_exposure.append(f"{row['table_name']}:{permission}")
                    primary_sequence_rows = (await primary_conn.execute(text(
                        """
                        SELECT n.nspname || '.' || c.relname AS sequence_name,
                               has_sequence_privilege(r.oid, c.oid, 'SELECT') AS can_select,
                               has_sequence_privilege(r.oid, c.oid, 'USAGE') AS can_use,
                               has_sequence_privilege(r.oid, c.oid, 'UPDATE') AS can_update
                        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                        JOIN pg_roles r ON r.rolname = CAST(:paper_role AS name)
                        WHERE n.nspname NOT LIKE 'pg_%'
                          AND n.nspname <> 'information_schema'
                          AND (NOT :same_database OR n.nspname <> 'customer_paper')
                          AND c.relkind = 'S'
                        """
                    ), {"paper_role": role_name, "same_database": same_database})).mappings().all()
                    for row in primary_sequence_rows:
                        for permission in ("can_select", "can_use", "can_update"):
                            if bool(row[permission]):
                                primary_exposure.append(f"{row['sequence_name']}:{permission}")
                    primary_security_definer_rows = (await primary_conn.execute(text(
                        """
                        SELECT n.nspname || '.' || p.proname AS function_name
                        FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                        JOIN pg_roles r ON r.rolname = CAST(:paper_role AS name)
                        WHERE n.nspname NOT LIKE 'pg_%'
                          AND n.nspname <> 'information_schema'
                          AND p.prosecdef
                          AND has_function_privilege(r.oid, p.oid, 'EXECUTE')
                        """
                    ), {"paper_role": role_name})).mappings().all()
                    for row in primary_security_definer_rows:
                        primary_exposure.append(f"{row['function_name']}:SECURITY_DEFINER_EXECUTE")
                    if primary_exposure:
                        return {
                            "status": "BLOCKED",
                            "reason": "PAPER_ROLE_HAS_PRIMARY_RELATION_PRIVILEGES",
                            "privileges": sorted(primary_exposure),
                        }
            finally:
                await primary_engine.dispose()
            return {
                "status": "PASS",
                "reason": (
                    "SHARED_DATABASE_SCHEMA_PREFLIGHT_PASS"
                    if same_database
                    else "ISOLATED_CUSTOMER_PAPER_DATABASE_PREFLIGHT_PASS"
                ),
                "identity": {"database": db_name, "role": role_name},
                "url_pair": pair,
                "isolation_mode": pair["isolation_mode"],
                "same_database_schema_isolation": same_database,
                "paper_tables": sorted(PAPER_TABLES),
                "paper_sequence_privileges": "USAGE_VERIFIED_FOR_ALL_FOUR_IDENTITY_SEQUENCES",
                "real_money_table_privileges": "NONE_FOR_ALL_EXISTING_CHECKED_TABLES",
                "primary_role_identity_check": (
                    "ROLE_PRESENT_PRIVILEGES_CHECKED"
                    if paper_role_present_on_primary
                    else "ROLE_ABSENT_FROM_PRIMARY_CLUSTER"
                ),
                "read_only_preflight": True,
                "enables_customer_paper_trading": False,
            }
    except Exception as exc:
        # Connectivity/auth failures are never accepted as proof of isolation.
        return {"status": "BLOCKED", "reason": "PAPER_DATABASE_PREFLIGHT_ERROR",
                "detail": type(exc).__name__}
    finally:
        await engine.dispose()


PAPER_ACCOUNT_CODES = frozenset({
    "PAPER_CASH", "PAPER_EQUITY", "PAPER_POSITION", "PAPER_FEES", "PAPER_PNL", "PAPER_CLEARING",
})
PAPER_EVENT_TYPES = frozenset({
    "PAPER_SEED", "SIMULATED_FILL", "SIMULATED_FEE",
    "SIMULATED_FUNDING", "SIMULATED_REALIZED_PNL", "REVERSAL", "RESET",
})
_CURRENCY_RE = re.compile(r"^[A-Z0-9]{2,12}$")
_AMOUNT_QUANTUM = Decimal("0.000000000000000001")


class CustomerPaperLedgerError(RuntimeError):
    """Base exception for a blocked or invalid customer paper-ledger operation."""


class CustomerPaperLedgerBlocked(CustomerPaperLedgerError):
    """Raised when the isolated paper database does not pass its live preflight."""


class CustomerPaperIdempotencyConflict(CustomerPaperLedgerError):
    """Raised when an idempotency key is reused for a different paper journal."""


def _validated_paper_journal(
    *,
    customer_id: int,
    idempotency_key: str,
    event_type: str,
    currency: str,
    lines: Sequence[Mapping[str, Any]],
    reference: str,
    metadata: Mapping[str, Any] | None,
) -> dict[str, Any]:
    if isinstance(customer_id, bool) or not isinstance(customer_id, int) or customer_id <= 0:
        raise ValueError("customer_id must be a positive integer")
    key = str(idempotency_key or "").strip()
    if not key or len(key) > 180:
        raise ValueError("idempotency_key must contain 1 to 180 characters")
    event = str(event_type or "").strip().upper()
    if event not in PAPER_EVENT_TYPES:
        raise ValueError("event_type is not an allowed customer paper-ledger event")
    normalized_currency = str(currency or "").strip().upper()
    if not _CURRENCY_RE.fullmatch(normalized_currency):
        raise ValueError("currency must be 2 to 12 uppercase alphanumeric characters")
    normalized_reference = str(reference or "").strip()
    if len(normalized_reference) > 180:
        raise ValueError("reference must not exceed 180 characters")
    if not isinstance(lines, Sequence) or isinstance(lines, (str, bytes)) or len(lines) < 2:
        raise ValueError("a balanced journal requires at least two lines")
    if metadata is not None and not isinstance(metadata, Mapping):
        raise ValueError("metadata must be a JSON-compatible mapping")
    user_metadata = dict(metadata or {})
    if "_paper_ledger_payload_sha256" in user_metadata:
        raise ValueError("metadata uses a reserved ledger integrity field")

    normalized_lines: list[dict[str, str]] = []
    seen_codes: set[str] = set()
    total = Decimal("0")
    for line in lines:
        if not isinstance(line, Mapping):
            raise ValueError("each journal line must be a mapping")
        account_code = str(line.get("account_code") or "").strip().upper()
        if account_code not in PAPER_ACCOUNT_CODES:
            raise ValueError("journal line uses an unsupported paper account code")
        if account_code in seen_codes:
            raise ValueError("a journal cannot contain duplicate account codes")
        seen_codes.add(account_code)
        raw_amount = line.get("signed_amount")
        if isinstance(raw_amount, (bool, float)) or not isinstance(raw_amount, (str, int, Decimal)):
            raise ValueError("signed_amount must be an exact decimal string, integer, or Decimal")
        try:
            amount = Decimal(str(raw_amount))
            if not amount.is_finite():
                raise ValueError("signed_amount must be finite")
            with localcontext() as ctx:
                ctx.prec = 50
                quantized = amount.quantize(_AMOUNT_QUANTUM)
        except (InvalidOperation, ValueError) as exc:
            if isinstance(exc, ValueError):
                raise
            raise ValueError("signed_amount is outside numeric(38,18) precision") from exc
        if quantized != amount or quantized == 0 or max(quantized.adjusted() + 1, 0) > 20:
            raise ValueError("signed_amount must be nonzero and exactly representable as numeric(38,18)")
        normalized_lines.append({"account_code": account_code, "signed_amount": format(quantized, "f")})
    with localcontext() as ctx:
        ctx.prec = 50
        total = sum((Decimal(line["signed_amount"]) for line in normalized_lines), Decimal("0"))
    if total != 0:
        raise ValueError("journal signed_amount values must sum exactly to zero")
    try:
        user_metadata_json = json.dumps(user_metadata, sort_keys=True, separators=(",", ":"), allow_nan=False)
    except (TypeError, ValueError) as exc:
        raise ValueError("metadata must be JSON serializable and finite") from exc
    payload = {
        "customer_id": customer_id, "idempotency_key": key, "event_type": event,
        "currency": normalized_currency, "reference": normalized_reference,
        "lines": normalized_lines, "metadata": json.loads(user_metadata_json),
    }
    digest = hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")
    ).hexdigest()
    return {
        **payload,
        "metadata_json": {**user_metadata, "_paper_ledger_payload_sha256": digest},
        "payload_sha256": digest,
    }


def _paper_engine():
    paper_url = settings.customer_paper_database_url
    if not paper_url:
        raise CustomerPaperLedgerBlocked("CUSTOMER_PAPER_DATABASE_URL is missing")
    if "+asyncpg" not in paper_url:
        try:
            paper_url = _postgres_url(paper_url).render_as_string(hide_password=False)
        except ValueError as exc:
            raise CustomerPaperLedgerBlocked("customer paper database URL is invalid") from exc
    return create_async_engine(
        paper_url,
        pool_pre_ping=True,
        connect_args={"server_settings": {"statement_timeout": "10000"}},
    )


async def _assert_customer_paper_ready() -> dict[str, Any]:
    result = await preflight_isolated_customer_paper_ledger(require_enabled=True)
    if result.get("status") != "PASS":
        raise CustomerPaperLedgerBlocked(
            f"customer paper ledger blocked: {result.get('reason', 'UNKNOWN')} "
            f"{result.get('detail', '')}".strip()
        )
    return result


async def post_customer_paper_journal(
    *,
    customer_id: int,
    idempotency_key: str,
    event_type: str,
    currency: str,
    lines: Sequence[Mapping[str, Any]],
    reference: str = "",
    metadata: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Post an immutable balanced journal only to the separately credentialed paper DB.

    Disabled/unconfigured operation fails closed. Each write reruns the isolation
    preflight, sets tenant RLS context transaction-locally, and avoids all real-money
    ledger sessions and tables.
    """
    normalized_event = str(event_type or "").strip().upper()
    if normalized_event != "PAPER_SEED":
        raise ValueError(
            "post_customer_paper_journal accepts only PAPER_SEED; fill and reversal "
            "journals must be created atomically by the customer-paper lifecycle"
        )
    payload = _validated_paper_journal(
        customer_id=customer_id,
        idempotency_key=idempotency_key,
        event_type=normalized_event,
        currency=currency,
        lines=lines,
        reference=reference,
        metadata=metadata,
    )
    seed_amounts = {
        item["account_code"]: Decimal(item["signed_amount"])
        for item in payload["lines"]
    }
    if (
        set(seed_amounts) != {"PAPER_CASH", "PAPER_EQUITY"}
        or seed_amounts["PAPER_CASH"] <= 0
        or seed_amounts["PAPER_EQUITY"] != -seed_amounts["PAPER_CASH"]
    ):
        raise ValueError(
            "PAPER_SEED must add positive PAPER_CASH balanced by the equal negative PAPER_EQUITY"
        )
    await _assert_customer_paper_ready()
    engine = _paper_engine()
    try:
        async with engine.begin() as conn:
            await conn.execute(
                text("SELECT set_config('app.customer_id', :customer_id, true)"),
                {"customer_id": str(customer_id)},
            )
            row = (await conn.execute(text(
                """
                INSERT INTO customer_paper.journals
                    (id, customer_id, idempotency_key, event_type, reference, metadata_json)
                VALUES
                    (:id, :customer_id, :idempotency_key, :event_type, :reference,
                     CAST(:metadata_json AS jsonb))
                ON CONFLICT (customer_id, idempotency_key) DO NOTHING
                RETURNING id
                """
            ), {
                "id": str(uuid.uuid4()),
                "customer_id": payload["customer_id"],
                "idempotency_key": payload["idempotency_key"],
                "event_type": payload["event_type"],
                "reference": payload["reference"],
                "metadata_json": json.dumps(
                    payload["metadata_json"], sort_keys=True, separators=(",", ":"), allow_nan=False
                ),
            })).first()
            if row is None:
                existing = (await conn.execute(text(
                    """
                    SELECT id, metadata_json, event_type, reference
                    FROM customer_paper.journals
                    WHERE customer_id = :customer_id AND idempotency_key = :idempotency_key
                    """
                ), {
                    "customer_id": payload["customer_id"],
                    "idempotency_key": payload["idempotency_key"],
                })).mappings().first()
                stored = existing["metadata_json"] if existing is not None else None
                if isinstance(stored, str):
                    try:
                        stored = json.loads(stored)
                    except ValueError:
                        stored = None
                stored_digest = stored.get("_paper_ledger_payload_sha256") if isinstance(stored, Mapping) else None
                if (
                    existing is None
                    or stored_digest != payload["payload_sha256"]
                    or str(existing["event_type"]) != payload["event_type"]
                    or str(existing["reference"]) != payload["reference"]
                ):
                    raise CustomerPaperIdempotencyConflict(
                        "idempotency key already exists for a different customer paper journal"
                    )
                return {
                    "status": "REPLAYED",
                    "journal_id": str(existing["id"]),
                    "idempotency_key": payload["idempotency_key"],
                    "payload_sha256": payload["payload_sha256"],
                }

            journal_id = str(row[0])
            account_ids: dict[str, int] = {}
            for line in payload["lines"]:
                code = line["account_code"]
                account_row = (await conn.execute(text(
                    """
                    INSERT INTO customer_paper.accounts
                        (customer_id, currency, account_code)
                    VALUES (:customer_id, :currency, :account_code)
                    ON CONFLICT (customer_id, currency, account_code) DO NOTHING
                    RETURNING id
                    """
                ), {
                    "customer_id": payload["customer_id"],
                    "currency": payload["currency"],
                    "account_code": code,
                })).first()
                if account_row is None:
                    account_row = (await conn.execute(text(
                        """
                        SELECT id FROM customer_paper.accounts
                        WHERE customer_id=:customer_id AND currency=:currency AND account_code=:account_code
                        """
                    ), {
                        "customer_id": payload["customer_id"],
                        "currency": payload["currency"],
                        "account_code": code,
                    })).first()
                if account_row is None:
                    raise CustomerPaperLedgerBlocked("paper account insert/read failed under tenant policy")
                account_ids[code] = int(account_row[0])

            for line in payload["lines"]:
                await conn.execute(text(
                    """
                    INSERT INTO customer_paper.journal_lines
                        (journal_id, account_id, customer_id, currency, signed_amount)
                    VALUES (:journal_id, :account_id, :customer_id, :currency, :signed_amount)
                    """
                ), {
                    "journal_id": journal_id,
                    "account_id": account_ids[line["account_code"]],
                    "customer_id": payload["customer_id"],
                    "currency": payload["currency"],
                    "signed_amount": Decimal(line["signed_amount"]),
                })
        return {
            "status": "APPENDED",
            "journal_id": journal_id,
            "idempotency_key": payload["idempotency_key"],
            "payload_sha256": payload["payload_sha256"],
        }
    finally:
        await engine.dispose()


async def get_customer_paper_balances(*, customer_id: int) -> list[dict[str, str]]:
    """Return exact per-account balances for only this customer in the paper ledger."""
    if isinstance(customer_id, bool) or not isinstance(customer_id, int) or customer_id <= 0:
        raise ValueError("customer_id must be a positive integer")
    await _assert_customer_paper_ready()
    engine = _paper_engine()
    try:
        async with engine.begin() as conn:
            await conn.execute(
                text("SELECT set_config('app.customer_id', :customer_id, true)"),
                {"customer_id": str(customer_id)},
            )
            rows = (await conn.execute(text(
                """
                SELECT a.currency, a.account_code, COALESCE(SUM(l.signed_amount), 0) AS balance
                FROM customer_paper.accounts a
                LEFT JOIN customer_paper.journal_lines l
                  ON l.account_id = a.id AND l.customer_id = a.customer_id AND l.currency = a.currency
                WHERE a.customer_id = :customer_id
                GROUP BY a.currency, a.account_code
                ORDER BY a.currency, a.account_code
                """
            ), {"customer_id": customer_id})).mappings().all()
        return [
            {
                "currency": str(row["currency"]),
                "account_code": str(row["account_code"]),
                "balance": format(Decimal(row["balance"]), "f"),
            }
            for row in rows
        ]
    finally:
        await engine.dispose()
